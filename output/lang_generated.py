# Estados de aceptación
ACCEPT: dict = {1: 'WS', 2: 'NEWLINE', 3: 'LPAREN', 4: 'RPAREN', 5: 'PLUS', 6: 'COMMA', 7: 'MINUS', 8: 'NUM', 9: 'SEMI', 10: 'ASSIGN', 11: 'ID', 12: 'ID', 13: 'ID', 14: 'ID', 15: 'ID', 16: 'ID', 17: 'ID', 18: 'ID', 19: 'ID', 20: 'ID', 21: 'ID', 22: 'ID', 23: 'LBRACKET', 24: 'RBRACKET', 25: 'LBRACE', 26: 'RBRACE', 27: 'DEF', 28: 'CLASS', 29: 'RETURN'}

START_STATE: int = 0


class LexError(Exception): pass


def yylex(text: str):
    """
    Tokeniza text y retorna lista de (token, lexema, linea).
    Lanza LexError si encuentra un caracter no reconocido.
    """
    pos = 0
    line = 1
    tokens = []
    while pos < len(text):
        line_at_token = line
        state     = START_STATE
        last_acc  = None
        i         = pos
        while i < len(text):
            ch = text[i]
            nxt = TRANSITIONS.get(state, {}).get(ch, -1)
            if nxt == -1:
                break
            state = nxt
            i += 1
            if state in ACCEPT:
                last_acc = (ACCEPT[state], i)
        if last_acc is None:
            raise LexError(f'Linea {line}: caracter no reconocido {repr(text[pos])}')
        tok, end = last_acc
        lexeme = text[pos:end]
        line += lexeme.count('\n')
        tokens.append((tok, lexeme, line_at_token))
        pos = end
    return tokens



def apply_actions(tokens: list):
    """Aplica las acciones definidas en el .yal a cada token."""
    results = []
    for tok, lexeme, line in tokens:
        lxm = lexeme
        result = _dispatch(tok, lxm)
        if result is not None:
            results.append((result, lxm, line) if isinstance(result, str) else (*result, line))
    return results


def _dispatch(tok: str, lxm: str):
    if tok == 'WS':
        return WS
        return lxm
    if tok == 'NEWLINE':
        return NEWLINE
        return lxm
    if tok == 'NUM':
        return NUM
        return lxm
    if tok == 'CLASS':
        return CLASS
        return lxm
    if tok == 'DEF':
        return DEF
        return lxm
    if tok == 'RETURN':
        return RETURN
        return lxm
    if tok == 'ID':
        return ID
        return lxm
    if tok == 'PLUS':
        return PLUS
        return lxm
    if tok == 'MINUS':
        return MINUS
        return lxm
    if tok == 'ASSIGN':
        return ASSIGN
        return lxm
    if tok == 'COMMA':
        return COMMA
        return lxm
    if tok == 'SEMI':
        return SEMI
        return lxm
    if tok == 'LPAREN':
        return LPAREN
        return lxm
    if tok == 'RPAREN':
        return RPAREN
        return lxm
    if tok == 'LBRACE':
        return LBRACE
        return lxm
    if tok == 'RBRACE':
        return RBRACE
        return lxm
    if tok == 'LBRACKET':
        return LBRACKET
        return lxm
    if tok == 'RBRACKET':
        return RBRACKET
        return lxm
    return (tok, lxm)


