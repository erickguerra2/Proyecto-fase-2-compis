# Estados de aceptación
ACCEPT: dict = {1: 'WS', 2: 'NEWLINE', 3: 'LPAREN', 4: 'RPAREN', 5: 'TIMES', 6: 'PLUS', 7: 'COMMA', 8: 'MINUS', 9: 'NUM', 10: 'SEMI', 11: 'ASSIGN', 12: 'ID', 13: 'ID', 14: 'ID', 15: 'ID', 16: 'ID', 17: 'ID', 18: 'ID', 19: 'ID', 20: 'ID', 21: 'ID', 22: 'ID', 23: 'ID', 24: 'LBRACKET', 25: 'RBRACKET', 26: 'LBRACE', 27: 'RBRACE', 28: 'DEF', 29: 'CLASS', 30: 'RETURN'}

START_STATE: int = 0


class LexError(Exception): pass


def yylex(text: str):
    """
    Tokeniza text y retorna lista de (token, lexema, linea, columna).
    Lanza LexError si encuentra un caracter no reconocido.
    """
    pos  = 0
    line = 1
    col  = 1
    tokens = []
    while pos < len(text):
        state     = START_STATE
        last_acc  = None
        i         = pos
        tok_line, tok_col = line, col
        while i < len(text):
            ch = text[i]
            nxt = TRANSITIONS.get(state, {}).get(ch, -1)
            if nxt == -1:
                break
            state = nxt
            i += 1
            if state in ACCEPT:
                last_acc = (ACCEPT[state], i)
        if last_acc is None:
            raise LexError(f'Error lexico en linea {line}, columna {col}: {repr(text[pos])}')
        tok, end = last_acc
        lexeme = text[pos:end]
        tokens.append((tok, lexeme, tok_line, tok_col))
        for ch in lexeme:
            if ch == '\n':
                line += 1
                col   = 1
            else:
                col  += 1
        pos = end
    return tokens



def apply_actions(tokens: list):
    """Aplica las acciones definidas en el .yal a cada token."""
    results = []
    for tok, lexeme in tokens:
        lxm = lexeme
        result = _dispatch(tok, lxm)
        if result is not None:
            results.append(result)
    return results


